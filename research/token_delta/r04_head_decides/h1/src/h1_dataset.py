"""R04/H1 preregistered synthetic computation tasks, without answer leakage.

1,200 train / 200 validation / 300 test. Four equal strata (math/code x EN/RU).
Every (operator, a, b, c) tuple occurs in exactly one prompt in one split.
The target is TWO computed decimal digits, never inserted into the question.
This is a diagnostic of short computed outputs, not general reasoning.
"""
from __future__ import annotations

import hashlib
import io
import itertools
import json
import random
import re
from contextlib import redirect_stdout
from pathlib import Path

DATASET_SEED = 20261012
SPLITS = {"train": 300, "val": 50, "test": 75}  # per (domain,language) bucket
OPERATIONS = ("add", "weighted")
DOMAINS = ("arithmetic", "code")
LANGUAGES = ("en", "ru")


def solve(op: str, a: int, b: int, c: int) -> tuple[int, int]:
    if op == "add":
        p = (a + b) % 10
        q = (p + c) % 10
    elif op == "weighted":
        p = (2 * a + b) % 10
        q = (p + 2 * c) % 10
    else:
        raise ValueError(f"invalid operator: {op}")
    return p, q


def python_code(op: str, a: int, b: int, c: int) -> str:
    if op not in OPERATIONS:
        raise ValueError(op)
    line = 'x = (x + y) % 10' if op == "add" else 'x = (2 * x + y) % 10'
    update = 'z = (x + z) % 10' if op == "add" else 'z = (x + 2 * z) % 10'
    return f'x = {a}\ny = {b}\nz = {c}\n{line}\n{update}\nprint(x, z)'


def verify_python(op: str, a: int, b: int, c: int) -> tuple[int, int]:
    """Executes ONLY the fixed template generated by this module; never user input."""
    stream = io.StringIO()
    with redirect_stdout(stream):
        exec(compile(python_code(op, a, b, c), '<generated-fixed-program>', 'exec'),
             {'__builtins__': {'print': print}}, {})
    out = stream.getvalue().strip().split()
    return tuple(int(v) for v in out)


def question(domain: str, language: str, op: str, a: int, b: int, c: int) -> str:
    p_expr = f'({a} + {b}) % 10' if op == 'add' else f'(2 * {a} + {b}) % 10'
    q_expr = '(p + ' + str(c) + ') % 10' if op == 'add' else '(p + 2 * ' + str(c) + ') % 10'
    if domain == 'arithmetic':
        body = f'p = {p_expr}\nq = {q_expr}\n'
        if language == 'en':
            return ('Solve the two-stage arithmetic problem. The operator % is remainder, '
                    'and q uses the computed value of p.\n' + body +
                    'Output the two final decimal DIGITS p and q separated by exactly one space. '
                    'No explanation, no other characters.')
        return ('Реши двухшаговую арифметическую задачу. Оператор % — остаток от деления, '
                'для q используется вычисленное p.\n' + body +
                'Выведи только две итоговые ЦИФРЫ p и q через один пробел, без пояснений и другого текста.')
    if domain == 'code':
        script = python_code(op, a, b, c)
        if language == 'en':
            return ('What does the following Python 3 program print? '
                    'Return only TWO decimal DIGITS separated by exactly one space; '
                    'no explanation.\n```python\n' + script + '\n```')
        return ('Что напечатает программа Python 3? '
                'Ответ — только ДВЕ десятичные ЦИФРЫ через один пробел, без пояснений.\n'
                '```python\n' + script + '\n```')
    raise ValueError(domain)


def build_dataset(seed: int = DATASET_SEED) -> list[dict]:
    rng = random.Random(seed)
    keys = list(itertools.product(OPERATIONS, range(20), range(20), range(20)))
    rng.shuffle(keys)
    required = len(DOMAINS) * len(LANGUAGES) * sum(SPLITS.values())
    assert len(keys) >= required
    examples: list[dict] = []
    cursor = 0
    for domain in DOMAINS:
        for language in LANGUAGES:
            for split, n in SPLITS.items():
                for _ in range(n):
                    op, a, b, c = keys[cursor]
                    cursor += 1
                    p, q = solve(op, a, b, c)
                    examples.append({
                        'id': f'h1-{len(examples):04d}',
                        'split': split, 'domain': domain, 'language': language,
                        'operator': op, 'operands': [a, b, c],
                        'group': f'{op}:{a}:{b}:{c}',
                        'question': question(domain, language, op, a, b, c),
                        'digits': [p, q], 'answer': f'{p} {q}',
                    })
    assert len(examples) == 1700
    assert len({e['group'] for e in examples}) == 1700
    return examples


def select_pilot(examples: list[dict], n: int) -> list[dict]:
    """Engineering pilots must only use TRAIN examples to keep H1 test sealed."""
    if not 1 <= n <= 16:
        raise ValueError('Engineering pilot size must be in 1..16')
    chosen = [x for x in examples if x['split'] == 'train'][:n]
    if len(chosen) != n:
        raise RuntimeError('Not enough train examples for pilot')
    return chosen

def strict_parse_answer(reply: str) -> list[int] | None:
    """Invalid or explained teacher outputs are scored as wrong, not cleaned up."""
    match = re.fullmatch(r'\s*([0-9])\s+([0-9])\s*', reply, flags=re.DOTALL)
    return [int(match.group(1)), int(match.group(2))] if match else None


def dataset_sha256(data: list[dict]) -> str:
    payload = json.dumps(data, ensure_ascii=False, sort_keys=True, separators=(',', ':'))
    return hashlib.sha256(payload.encode('utf-8')).hexdigest()


def materialize(destination: Path, seed: int = DATASET_SEED) -> dict:
    data = build_dataset(seed)
    destination.mkdir(parents=True, exist_ok=True)
    path = destination / 'h1_dataset.jsonl'
    with path.open('w', encoding='utf-8', newline='\n') as stream:
        for record in data:
            stream.write(json.dumps(record, ensure_ascii=False, sort_keys=True) + '\n')
    manifest = {
        'status': 'generated_oracle_data_not_model_results',
        'seed': seed, 'count': len(data),
        'splits': {part: sum(x['split'] == part for x in data) for part in SPLITS},
        'dataset_sha256_canonical': dataset_sha256(data),
        'file_sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
        'output_tokenization_unknown_until_teacher_loaded': True,
    }
    (destination / 'dataset_manifest.json').write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
    return manifest


def load_dataset(destination: Path) -> tuple[list[dict], dict]:
    manifest = json.loads((destination / 'dataset_manifest.json').read_text(encoding='utf-8'))
    source = destination / 'h1_dataset.jsonl'
    if hashlib.sha256(source.read_bytes()).hexdigest() != manifest['file_sha256']:
        raise RuntimeError('Dataset bytes changed! Abort.')
    data = [json.loads(row) for row in source.read_text(encoding='utf-8').splitlines()]
    if dataset_sha256(data) != manifest['dataset_sha256_canonical']:
        raise RuntimeError('Dataset content changed! Abort: reproducibility compromised.')
    return data, manifest


